"""Redraw the gallery: a picture for every built-in source and shaper, and the page that shows them.

    uv run poe gallery

`examples/gallery/NAME.toml` is a patch with a node called NAME that uses the source or shaper NAME; its other nodes
feed it. Every signal node of it is drawn over `SECONDS` into `docs/gallery/NAME.png`, and `docs/gallery.md` lists the
pictures with their summaries and patches, sources first. A gallery patch holds its own data: none reads a bundle.
Needs matplotlib (`uv sync` installs it). `poe new-source` writes the patch of a new source or shaper.

Interface: `write_gallery(root)` writes pictures and page under `root` and returns their paths; `page(root)` is the
text of the page alone (a test checks the committed page against it, since a picture depends on the drawing library).
"""

from pathlib import Path

from bullterrier_control import load_patch, registry
from bullterrier_control.plotting import plot

ROOT = Path(__file__).resolve().parent.parent
SECONDS = 4.0  # the range every picture draws, from 0


def _patches(root: Path) -> list[tuple[str, Path]]:
    """(name, patch file) of every gallery patch, sources first, each group by name. `UnknownNameError` for a patch
    whose name is not registered: a stale file is a mistake, not something to skip."""
    found = [(path.stem, path) for path in (root / "examples" / "gallery").glob("*.toml")]
    return sorted(found, key=lambda item: (registry.get(item[0]).kind != "source", item[0]))


def page(root: Path) -> str:
    """The text of `docs/gallery.md` for the patches under `root`."""
    lines = [
        "# Gallery",
        "",
        f"One picture per source and shaper, drawn from the patch under it over {SECONDS:g} seconds:",
        "`uv run bt-control plot examples/gallery/NAME.toml --to 4 --out NAME.png`. A shaper's picture shows its input",
        "as well. Generated by `uv run poe gallery`; edit the patches, not this page.",
    ]
    heading = ""
    for name, path in _patches(root):
        thing = registry.get(name)
        if thing.kind != heading:
            heading = thing.kind
            lines += ["", f"## {heading.title()}s"]
        text = path.read_text(encoding="utf-8").rstrip("\n")
        lines += [
            "",
            f"### `{name}`",
            "",
            thing.summary,
            "",
            f"![{name}](gallery/{name}.png)",
            "",
            "```toml",
            text,
            "```",
        ]
    return "\n".join(lines) + "\n"


def write_gallery(root: Path) -> list[Path]:
    """Draw every picture and write the page under `root`; the paths written."""
    pictures = root / "docs" / "gallery"
    pictures.mkdir(parents=True, exist_ok=True)
    written = []
    for name, path in _patches(root):
        patch = load_patch(path)
        curves = {node: signal for node, signal in patch.build().items() if patch.nodes[node].returns == "signal"}
        picture = pictures / f"{name}.png"
        plot(curves, start=0.0, stop=SECONDS, path=picture, title=name)
        written.append(picture)
    (root / "docs" / "gallery.md").write_text(page(root), encoding="utf-8")
    return [*written, root / "docs" / "gallery.md"]


if __name__ == "__main__":
    for written in write_gallery(ROOT):
        print(f"wrote {written.relative_to(ROOT).as_posix()}")
