"""Write the typed face of `lib` and the chain methods of `Signal` from the built-in sources, shapers and operations.

    uv run poe api                              # rewrite both files
    uv run python tools/gen_api.py --check      # exit 1 naming each stale file (tests/tools/test_gen_api.py runs it)

`src/bullterrier_control/lib.pyi` has a typed function for every built-in source, shaper and operation, and
`__getattr__` for the rest (an installed package's: the registry entry, untyped). `src/bullterrier_control/_chain.py`
has `Chain`, which `Signal` inherits: a typed method for every built-in shaper, which applies the shaper registered
under its name. Both are made from what each one publishes (`Registered.description()`: parameter types, choices,
defaults, units, ranges, docs, and its inputs), never from its code, and are written as `ruff format` lays them out. A
plugin's are left out: it is reached as `lib.<name>` and through `signal.pipe`.

`render` refuses (`ValueError` naming the built-in or file) any text that does not compile: summaries and parameter
docs go into docstrings as they are, so a stray triple quote or a bad escape would otherwise write an invalid file.
If `_chain.py` is broken, restore it with `git checkout -- src/bullterrier_control/_chain.py` and rerun
`uv run poe api` (`signal.py` imports it, so the generator cannot start without it).

Interface: `render(registered)` -> {path from the checkout's root: text}; `main(argv)` -> exit code (0 written or
current, 1 stale).
"""

import argparse
import ast
import builtins
import json
import sys
import textwrap
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from bullterrier_control.inputs import INPUTS
from bullterrier_control.registry import Registered, all_registered
from bullterrier_control.signal import Signal

ROOT = Path(__file__).resolve().parent.parent
LIB = Path("src/bullterrier_control/lib.pyi")
CHAIN = Path("src/bullterrier_control/_chain.py")
BUILT_IN = "bullterrier_control.builtin."  # the modules a built-in is defined in
WIDTH = 120  # ruff's line length (pyproject.toml)
HEADER = "# Generated by `uv run poe api` (tools/gen_api.py) from the built-ins' descriptions: do not edit."
TYPES = {"number": "float", "integer": "int", "boolean": "bool", "string": "str"}  # JSON Schema type -> Python
RETURNS = {"signal": "Signal", "events": "tuple[Event, ...]", "series": "Series"}  # `Registered.returns` -> Python
# the module each name an annotation may use is imported from (a relative one is the package's)
ORIGINS = {
    "abstractmethod": "abc",
    "Any": "typing",
    "Literal": "typing",
    "Mapping": "collections.abc",
    "Sequence": "collections.abc",
    "Event": ".formats",
    "Grid": ".formats",
    "Series": ".formats",
    "Keyframe": ".inputs",
    "Registered": ".registry",
    "Signal": ".signal",
}


@dataclass(frozen=True)
class Argument:
    """One keyword a function takes: its annotation, default (source text, `None` when required) and docstring line."""

    name: str
    annotation: str
    default: str | None
    doc: str

    def declared(self) -> str:
        """As written in a signature."""
        return f"{self.name}: {self.annotation}" + ("" if self.default is None else f" = {self.default}")


def render(registered: Mapping[str, Registered[Any, Any]]) -> dict[Path, str]:
    """The text of `lib.pyi` and `_chain.py` for the built-ins among `registered`, by path from the root.

    `ValueError` for a built-in shaper named like an attribute `Signal` has already, or a parameter whose schema has no
    Python type here."""
    built_ins = {
        name: one for name, one in sorted(registered.items()) if (one.function.__module__ or "").startswith(BUILT_IN)
    }
    taken = {name for kind in Signal.__mro__ if kind.__module__ != "bullterrier_control._chain" for name in vars(kind)}
    shapers = {name: one for name, one in built_ins.items() if one.kind == "shaper"}
    for name in shapers:
        if name in taken:
            raise ValueError(
                f"shaper {name!r}: Signal has an attribute of that name already; name the shaper otherwise"
            )
    files = {LIB: _lib(built_ins), CHAIN: _chain(shapers)}
    for path, text in files.items():
        _check_compiles(path.as_posix(), text)
    return files


def _check_compiles(label: str, text: str) -> None:
    """`ValueError` naming `label` if `text` is not valid Python."""
    try:
        compile(textwrap.dedent(text), label, "exec")
    except SyntaxError as error:
        raise ValueError(
            f"{label}: the generated text does not compile ({error.msg}, line {error.lineno}); "
            "look for a quote or a backslash in its summary or parameter docs"
        ) from error


def _arguments(one: Registered[Any, Any]) -> list[Argument]:
    """The inputs, then the parameters, of `one`, from its description."""
    described = one.description()
    arguments = []
    for name, given in described["inputs"].items():
        required = given["required"]
        annotation = INPUTS[name].annotation + ("" if required else " | None")
        doc = f"{'required' if required else 'optional'}. {given['doc']}"
        arguments.append(Argument(name, annotation, None if required else "None", f"{name}: {doc}"))
    for name, schema in described["parameters"]["properties"].items():
        arguments.append(_parameter(name, schema))
    return arguments


def _parameter(name: str, schema: Mapping[str, Any]) -> Argument:
    """A parameter from its JSON Schema. A choice is `enum`, or `const` for one choice (which pydantic writes with or
    without an `enum` beside it, depending on its version); limits are numbers either way, shown as `:g`."""
    choices = schema["enum"] if "enum" in schema else [schema["const"]] if "const" in schema else None
    if choices is not None:
        annotation = f"Literal[{', '.join(json.dumps(choice) for choice in choices)}]"
    elif schema.get("type") in TYPES:
        annotation = TYPES[schema["type"]]
    else:
        raise ValueError(f"parameter {name!r}: no Python type for the schema {dict(schema)!r}")
    default = float(schema["default"]) if annotation == "float" else schema["default"]
    written = json.dumps(default, ensure_ascii=False) if isinstance(default, str) else repr(default)
    measure = f"{schema['unit']}, {schema['minimum']:g} to {schema['maximum']:g}, " if "minimum" in schema else ""
    flags = "".join(f", {flag}" for flag in ("advanced", "cyclic") if schema.get(flag))
    doc = f"{name}: {measure}default {default!r}{flags}. {schema['description']}"
    return Argument(name, annotation, written, doc)


def _signature(indent: str, head: str, arguments: list[str], returns: str) -> list[str]:
    """`head(arguments) -> returns:`, on one line if it fits, else as `ruff format` splits it."""
    return _bracketed(indent, f"{head}(", arguments, f") -> {returns}:")


def _bracketed(indent: str, opening: str, items: list[str], closing: str) -> list[str]:
    """`opening items closing` laid out as `ruff format` does: on one line, else the items on one line of their own,
    else one per line with a trailing comma."""
    one_line = f"{indent}{opening}{', '.join(items)}{closing}"
    if len(one_line) <= WIDTH:
        return [one_line]
    inner = f"{indent}    {', '.join(items)}"
    if len(inner) <= WIDTH:
        return [f"{indent}{opening}", inner, f"{indent}{closing}"]
    return [f"{indent}{opening}", *(f"{indent}    {item}," for item in items), f"{indent}{closing}"]


def _keywords(arguments: list[Argument]) -> list[str]:
    return ["*", *(argument.declared() for argument in arguments)] if arguments else []


def _docstring(indent: str, summary: str, arguments: list[Argument]) -> list[str]:
    """The summary, then an `Args:` line per argument, wrapped to the line length."""
    lines = textwrap.wrap(summary, WIDTH - len(indent) - 3, break_long_words=False, break_on_hyphens=False)
    lines = [f"{indent}{line}" for line in lines]
    lines[0] = f'{indent}"""{lines[0].lstrip()}'
    if not arguments:
        if len(lines) == 1 and len(lines[0]) + 3 <= WIDTH:
            return [lines[0] + '"""']
        return [*lines, f'{indent}"""']
    lines += ["", f"{indent}Args:"]
    for argument in arguments:
        lines += textwrap.wrap(
            argument.doc,
            WIDTH,
            initial_indent=indent + " " * 4,
            subsequent_indent=indent + " " * 8,
            break_long_words=False,
            break_on_hyphens=False,
        )
    return [*lines, f'{indent}"""']


def _imports(annotations: list[str]) -> list[str]:
    """The import lines (isort's order, as ruff wants it) for the names `annotations` use."""
    used = {
        node.id for text in annotations for node in ast.walk(ast.parse(text, mode="eval")) if isinstance(node, ast.Name)
    }
    unknown = sorted(used - ORIGINS.keys() - set(dir(builtins)))
    if unknown:
        raise ValueError(f"no import known for {unknown[0]!r}: add it to ORIGINS in tools/gen_api.py")
    modules: dict[str, list[str]] = {}
    for name in sorted(used & ORIGINS.keys()):
        modules.setdefault(ORIGINS[name], []).append(name)
    groups = [
        sorted(module for module in modules if not module.startswith(".")),
        sorted(m for m in modules if m.startswith(".")),
    ]
    lines: list[str] = []
    for group in groups:
        if group and lines:
            lines.append("")
        lines += [f"from {module} import {', '.join(modules[module])}" for module in group]
    return lines


def _lib(built_ins: Mapping[str, Registered[Any, Any]]) -> str:
    functions: list[list[str]] = []
    annotations = ["Registered[Any, Any]"]
    for name, one in built_ins.items():
        arguments = _arguments(one)
        signal = ["signal: Signal", "/"] if one.kind == "shaper" else []
        returns = RETURNS[one.returns]
        annotations += [returns, *(argument.annotation for argument in arguments), *(["Signal"] if signal else [])]
        signature = _signature("", f"def {name}", [*signal, *_keywords(arguments)], returns)
        function = [*signature, *_docstring("    ", one.summary, arguments)]
        _check_compiles(f"{one.kind} {name!r}", "\n".join(function))
        functions.append(function)
    lines = [
        HEADER,
        '"""The typed functions of `lib`: one per built-in source, shaper and operation; any other name (an installed',
        'package\'s) is the registry entry."""',
        "",
        *_imports(annotations),
    ]
    for function in functions:  # a stub separates them by one blank line, as `ruff format` does
        lines += ["", *function]
    lines += ["", "def __getattr__(name: str) -> Registered[Any, Any]: ..."]
    return "\n".join(lines) + "\n"


def _chain(shapers: Mapping[str, Registered[Any, Any]]) -> str:
    methods: list[list[str]] = []
    annotations = ["abstractmethod"]  # the one name the fixed part of the file needs
    for name, one in shapers.items():
        arguments = _arguments(one)
        annotations += [argument.annotation for argument in arguments]
        signature = _signature("    ", f"def {name}", ["self", *_keywords(arguments)], "S")
        call = _bracketed(
            "        ", "return self._apply(", [json.dumps(name), *(f"{a.name}={a.name}" for a in arguments)], ")"
        )
        method = [*signature, *_docstring("        ", one.summary, arguments), *call]
        _check_compiles(f"shaper {name!r}", "\n".join(method))
        methods.append(method)
    lines = [
        HEADER,
        '"""The chain methods of `Signal`: one per built-in shaper (`energy.slew(rise=0.2)`), each applying the shaper',
        'registered under its name. A plugin\'s shaper is applied with `signal.pipe(lib.<name>, ...)`."""',
        "",
        *_imports(annotations),
        "",
        "",
        "class Chain[S]:",
        '    """A method per built-in shaper, which `Signal` inherits as `Chain["Signal"]`: each gives a `Signal`',
        "    (`S`, a parameter only so that this module, which `signal` imports, imports nothing of it).",
        "",
        "    The signatures are for literal calls: a misspelt keyword is a type error, and a `TypeError` when run.",
        "    Parameters that come from data (a config dict) go through `lib.<name>` or `signal.pipe(lib.<name>,",
        '    **params)`, which raise `ParameterError` naming the field."""',
        "",
        "    @abstractmethod",
        "    def _apply(self, name: str, /, **params: object) -> S:",
        '        """The registered shaper `name` applied to this signal with `params`."""',
    ]
    for method in methods:
        lines += ["", *method]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write both files, or with `--check` say which differ from what the built-ins make."""
    parser = argparse.ArgumentParser(prog="gen_api.py", description="Write lib.pyi and _chain.py from the built-ins.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 naming each stale file")
    parser.add_argument(
        "--root", type=Path, default=ROOT, help="the checkout to write into or check (default: this one)"
    )
    args = parser.parse_args(argv)
    files = render(all_registered())
    if args.check:
        stale = [path for path, text in files.items() if not _holds(args.root / path, text)]
        for path in stale:
            print(f"{path.as_posix()} is stale: run `uv run poe api`", file=sys.stderr)
        return 1 if stale else 0
    for path, text in files.items():
        (args.root / path).parent.mkdir(parents=True, exist_ok=True)
        (args.root / path).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.as_posix()}")
    return 0


def _holds(path: Path, text: str) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8") == text


if __name__ == "__main__":
    sys.exit(main())
